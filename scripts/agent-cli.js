#!/usr/bin/env node
/**
 * NovaCPP Agent Management CLI Suite
 * Supports: install, list, doctor, update
 */

import fs from "fs-extra";
import path from "path";
import os from "os";
import crypto from "crypto";
import { execSync } from "child_process";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, "..");
const AGENT_DIST = path.join(REPO_ROOT, "agent", "dist");
const SKILLS_SRC = path.join(REPO_ROOT, "agent", "skills");

const HEADER_NOTICE = "<!-- generated by nova agent; edits will be overwritten by 'nova agent update' -->\n\n";

function ensureDistExists() {
    if (!fs.existsSync(AGENT_DIST) || !fs.existsSync(path.join(AGENT_DIST, "root", "AGENTS.md"))) {
        const buildScript = path.join(REPO_ROOT, "agent", "tools", "build.py");
        if (fs.existsSync(buildScript)) {
            try {
                execSync(`python "${buildScript}"`, { stdio: "inherit" });
            } catch (e) {
                console.error("[ERROR] Failed to compile agent adapters with build.py");
            }
        }
    }
}

function computeHash(content) {
    return crypto.createHash("sha256").update(content).digest("hex").slice(0, 16);
}

function detectInstalledAgents(targetDir) {
    const detected = [];
    if (fs.existsSync(path.join(targetDir, ".agent")) || fs.existsSync(path.join(targetDir, ".agents"))) {
        detected.push("antigravity");
    }
    if (fs.existsSync(path.join(targetDir, ".claude")) || fs.existsSync(path.join(targetDir, "CLAUDE.md"))) {
        detected.push("claude");
    }
    if (fs.existsSync(path.join(targetDir, ".cursor"))) {
        detected.push("cursor");
    }
    if (fs.existsSync(path.join(targetDir, ".github"))) {
        detected.push("copilot");
    }
    if (fs.existsSync(path.join(targetDir, ".windsurf"))) {
        detected.push("windsurf");
    }
    if (detected.length === 0) {
        // Default agent triad for NovaCPP projects
        return ["antigravity", "claude", "cursor"];
    }
    return detected;
}

export async function runAgentCommand(args, targetDir = process.cwd()) {
    const subcommand = args[0] || "help";
    ensureDistExists();

    if (subcommand === "install") {
        await handleInstall(args.slice(1), targetDir);
    } else if (subcommand === "list") {
        await handleList(targetDir);
    } else if (subcommand === "doctor") {
        await handleDoctor(targetDir);
    } else if (subcommand === "update") {
        await handleUpdate(args.slice(1), targetDir);
    } else {
        printHelp();
    }
}

async function handleInstall(args, targetDir) {
    let targetAgents = [];
    const isGlobal = args.includes("--global");

    const agentIdx = args.indexOf("--agent");
    if (agentIdx !== -1 && args[agentIdx + 1]) {
        const requested = args[agentIdx + 1].toLowerCase();
        if (requested === "all") {
            targetAgents = ["antigravity", "claude", "cursor", "copilot", "windsurf"];
        } else {
            targetAgents = requested.split(",").map(a => a.trim()).filter(Boolean);
        }
    } else {
        targetAgents = detectInstalledAgents(targetDir);
    }

    console.log("======================================================================");
    console.log(`  NovaCPP Agent Skills Installer (${isGlobal ? "Global" : "Workspace"})`);
    console.log("======================================================================");
    console.log(`  Target Directory: ${targetDir}`);
    console.log(`  Target Agents:    ${targetAgents.join(", ")}\n`);

    const installedSkillsCount = fs.readdirSync(SKILLS_SRC).filter(d => fs.statSync(path.join(SKILLS_SRC, d)).isDirectory()).length;
    let totalFilesWritten = 0;

    if (isGlobal) {
        const home = os.homedir();
        if (targetAgents.includes("antigravity") || targetAgents.includes("all")) {
            const agGlobal = path.join(home, ".gemini", "antigravity", "skills");
            await fs.copy(path.join(AGENT_DIST, "antigravity", ".agent", "skills"), agGlobal, { overwrite: true });
            console.log(`  [OK] Installed ${installedSkillsCount} skills to Google Antigravity global: ${agGlobal}`);
        }
        if (targetAgents.includes("claude") || targetAgents.includes("all")) {
            const claudeGlobal = path.join(home, ".claude", "skills");
            await fs.copy(path.join(AGENT_DIST, "claude", ".claude", "skills"), claudeGlobal, { overwrite: true });
            console.log(`  [OK] Installed ${installedSkillsCount} skills to Claude Code global: ${claudeGlobal}`);
        }
        if (targetAgents.includes("cursor") || targetAgents.includes("all")) {
            const cursorGlobal = path.join(home, ".cursor", "rules");
            await fs.copy(path.join(AGENT_DIST, "cursor", ".cursor", "rules"), cursorGlobal, { overwrite: true });
            console.log(`  [OK] Installed Cursor rules to global: ${cursorGlobal}`);
        }
    } else {
        // Workspace installation
        // Always place root AGENTS.md
        const rootAgentsSrc = path.join(AGENT_DIST, "root", "AGENTS.md");
        const rootAgentsDst = path.join(targetDir, "AGENTS.md");
        if (fs.existsSync(rootAgentsSrc)) {
            const content = HEADER_NOTICE + fs.readFileSync(rootAgentsSrc, "utf-8");
            await fs.writeFile(rootAgentsDst, content, "utf-8");
            totalFilesWritten++;
        }

        for (const agent of targetAgents) {
            if (agent === "antigravity") {
                const agDst1 = path.join(targetDir, ".agent");
                const agDst2 = path.join(targetDir, ".agents");
                await fs.copy(path.join(AGENT_DIST, "antigravity", ".agent"), agDst1, { overwrite: true });
                await fs.copy(path.join(AGENT_DIST, "agents", ".agents"), agDst2, { overwrite: true });
                console.log(`  [OK] Google Antigravity: Configured .agent/ and .agents/ (${installedSkillsCount} skills + rules/nova.md)`);
                totalFilesWritten += (installedSkillsCount * 2 + 1);
            } else if (agent === "claude") {
                const claudeDst = path.join(targetDir, ".claude");
                await fs.copy(path.join(AGENT_DIST, "claude", ".claude"), claudeDst, { overwrite: true });
                const claudeMdDst = path.join(targetDir, "CLAUDE.md");
                await fs.writeFile(claudeMdDst, HEADER_NOTICE + "@AGENTS.md\n", "utf-8");
                console.log(`  [OK] Claude Code: Configured .claude/skills/ and CLAUDE.md`);
                totalFilesWritten += (installedSkillsCount + 1);
            } else if (agent === "cursor") {
                const cursorDst = path.join(targetDir, ".cursor");
                await fs.copy(path.join(AGENT_DIST, "cursor", ".cursor"), cursorDst, { overwrite: true });
                console.log(`  [OK] Cursor: Configured .cursor/rules/ (23 .mdc rules)`);
                totalFilesWritten += 23;
            } else if (agent === "copilot") {
                const ghDst = path.join(targetDir, ".github");
                await fs.copy(path.join(AGENT_DIST, "copilot", ".github"), ghDst, { overwrite: true });
                console.log(`  [OK] GitHub Copilot: Configured .github/copilot-instructions.md & .github/instructions/`);
                totalFilesWritten += (installedSkillsCount + 1);
            } else if (agent === "windsurf") {
                const wsDst = path.join(targetDir, ".windsurf");
                await fs.copy(path.join(AGENT_DIST, "windsurf", ".windsurf"), wsDst, { overwrite: true });
                console.log(`  [OK] Windsurf: Configured .windsurf/rules/`);
                totalFilesWritten += installedSkillsCount;
            }
        }

        // Write .nova-agent.json manifest
        const manifest = {
            version: "2.1.1",
            installed_at: new Date().toISOString(),
            agents: targetAgents,
            skills_count: installedSkillsCount,
            manifest_hash: computeHash(targetAgents.join(",") + ":" + installedSkillsCount)
        };
        await fs.writeJson(path.join(targetDir, ".nova-agent.json"), manifest, { spaces: 2 });
    }

    console.log("\n======================================================================");
    console.log(`  INSTALLATION COMPLETE (${totalFilesWritten} files synchronized)`);
    console.log("======================================================================");
    console.log("  Assistant Environment Recommendations:");
    if (targetAgents.includes("antigravity")) {
        console.log("  - Google Antigravity: Window reloaded automatically or run /reload.");
    }
    if (targetAgents.includes("claude")) {
        console.log("  - Claude Code: Skills automatically active in next turn.");
    }
    if (targetAgents.includes("cursor")) {
        console.log("  - Cursor: Rules active across all chat conversations.");
    }
}

async function handleList(targetDir) {
    console.log("======================================================================");
    console.log("  NovaCPP Installed Agent Skills Status");
    console.log("======================================================================");

    const manifestPath = path.join(targetDir, ".nova-agent.json");
    if (fs.existsSync(manifestPath)) {
        const m = await fs.readJson(manifestPath);
        console.log(`  Framework Version: ${m.version}`);
        console.log(`  Installed At:      ${m.installed_at}`);
        console.log(`  Active Agents:     ${m.agents.join(", ")}`);
        console.log(`  Total Skills:      ${m.skills_count}`);
        console.log(`  Manifest Hash:     ${m.manifest_hash}`);
    } else {
        console.log("  Notice: No .nova-agent.json manifest found in current directory.");
        console.log("  Running environment detection...");
        const agents = detectInstalledAgents(targetDir);
        console.log(`  Detected Active Folders: ${agents.join(", ")}`);
    }
    console.log("======================================================================");
}

async function handleDoctor(targetDir) {
    console.log("======================================================================");
    console.log("  NovaCPP Agent Environment Doctor & Healthcheck");
    console.log("======================================================================");

    let issues = 0;

    // 1. Check root AGENTS.md
    const agentsMd = path.join(targetDir, "AGENTS.md");
    if (fs.existsSync(agentsMd)) {
        console.log("  [PASS] Root AGENTS.md router present and readable.");
    } else {
        console.log("  [WARN] Root AGENTS.md missing (run 'nova agent install' to generate).");
        issues++;
    }

    // 2. Check .nova-agent.json
    const manifestPath = path.join(targetDir, ".nova-agent.json");
    if (fs.existsSync(manifestPath)) {
        const m = await fs.readJson(manifestPath);
        console.log(`  [PASS] .nova-agent.json manifest valid (v${m.version}, ${m.skills_count} skills).`);

        for (const ag of m.agents) {
            if (ag === "antigravity") {
                const agSkills = path.join(targetDir, ".agent", "skills");
                const count = fs.existsSync(agSkills) ? fs.readdirSync(agSkills).length : 0;
                if (count >= 20) {
                    console.log(`  [PASS] Google Antigravity: .agent/skills/ populated (${count} skills).`);
                } else {
                    console.log(`  [FAIL] Google Antigravity: .agent/skills/ incomplete (${count} skills).`);
                    issues++;
                }
            } else if (ag === "claude") {
                const clSkills = path.join(targetDir, ".claude", "skills");
                const count = fs.existsSync(clSkills) ? fs.readdirSync(clSkills).length : 0;
                if (count >= 20 && fs.existsSync(path.join(targetDir, "CLAUDE.md"))) {
                    console.log(`  [PASS] Claude Code: .claude/skills/ and CLAUDE.md healthy.`);
                } else {
                    console.log(`  [FAIL] Claude Code: .claude/skills/ or CLAUDE.md missing.`);
                    issues++;
                }
            } else if (ag === "cursor") {
                const crRules = path.join(targetDir, ".cursor", "rules");
                const count = fs.existsSync(crRules) ? fs.readdirSync(crRules).length : 0;
                if (count >= 20) {
                    console.log(`  [PASS] Cursor: .cursor/rules/ healthy (${count} rules).`);
                } else {
                    console.log(`  [FAIL] Cursor: .cursor/rules/ incomplete (${count} rules).`);
                    issues++;
                }
            }
        }
    } else {
        console.log("  [WARN] .nova-agent.json manifest not found.");
        issues++;
    }

    console.log("======================================================================");
    if (issues === 0) {
        console.log("  HEALTHCHECK RESULT: ALL AGENT SKILL SYSTEMS HEALTHY!");
    } else {
        console.log(`  HEALTHCHECK RESULT: ${issues} WARNING(S) FOUND. Run 'nova agent update'.`);
    }
    console.log("======================================================================");
}

async function handleUpdate(args, targetDir) {
    console.log("[NovaCPP] Refreshing agent adapters from canonical skills...");
    const manifestPath = path.join(targetDir, ".nova-agent.json");
    let agents = [];
    if (fs.existsSync(manifestPath)) {
        try {
            const m = await fs.readJson(manifestPath);
            agents = m.agents || [];
        } catch (e) {}
    }
    const installArgs = agents.length > 0 ? ["--agent", agents.join(",")] : [];
    await handleInstall(installArgs, targetDir);
}

function printHelp() {
    console.log("Usage: nova agent <subcommand> [options]\n");
    console.log("Subcommands:");
    console.log("  install    Install skills into active workspace (auto-detects agent or use --agent)");
    console.log("  list       List installed agent adapters and skill counts");
    console.log("  doctor     Audit file integrity, hashes, and session hints");
    console.log("  update     Update installed skills to match the active Nova framework version\n");
    console.log("Options:");
    console.log("  --agent <name>   Target agent: antigravity, claude, cursor, copilot, windsurf, all");
    console.log("  --global         Install into user-level global configuration folders\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    runAgentCommand(process.argv.slice(2));
}
